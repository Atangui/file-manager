// Extracts t('…') / tn('…', '…', n) calls from the app sources into includes/i18n-strings.php,
// so JavaScript strings are translated through regular gettext (.po/.mo files).
import { readFileSync, writeFileSync, readdirSync, statSync } from 'node:fs';
import { join } from 'node:path';

const SRC = 'assets/src/app';
const OUT = 'includes/i18n-strings.php';

const files = [];
const walk = (dir) => {
  for (const name of readdirSync(dir)) {
    const path = join(dir, name);
    if (statSync(path).isDirectory()) walk(path);
    else if (/\.(jsx?|mjs)$/.test(name)) files.push(path);
  }
};
walk(SRC);

const unescape = (s) => s.replace(/\\(.)/g, (_, c) => ({ n: '\n', t: '\t' }[c] ?? c));
const php = (s) => "'" + s.replace(/\\/g, '\\\\').replace(/'/g, "\\'") + "'";
const STR = String.raw`(['"\x60])((?:\\.|(?!\1)[^\\])*?)\1`;
const single = new RegExp(String.raw`\bt\(\s*` + STR + String.raw`\s*[,)]`, 'g');
const plural = new RegExp(String.raw`\btn\(\s*` + STR + String.raw`\s*,\s*` + STR.replace(/\\1/g, '\\3'), 'g');

const singles = new Map();
const plurals = new Map();
for (const file of files.sort()) {
  const code = readFileSync(file, 'utf8');
  for (const m of code.matchAll(single)) {
    if (m[1] === '`' && m[2].includes('${')) continue;
    singles.set(unescape(m[2]), file);
  }
  for (const m of code.matchAll(plural)) {
    plurals.set(unescape(m[2]), unescape(m[4]));
  }
}

let out = "<?php\n/**\n * Generated by bin/extract-strings.mjs — do not edit by hand.\n *\n * @package Filora\n */\n\n// phpcs:ignoreFile\ndefined( 'ABSPATH' ) || exit;\n\nreturn array(\n";
for (const s of [...singles.keys()].sort()) {
  if (plurals.has(s)) continue;
  out += `\t${php(s)} => __( ${php(s)}, 'filora' ),\n`;
}
for (const [s, p] of [...plurals.entries()].sort()) {
  out += `\t${php(s)} => array( _n( ${php(s)}, ${php(p)}, 1, 'filora' ), _n( ${php(s)}, ${php(p)}, 2, 'filora' ) ),\n`;
}
out += ');\n';
writeFileSync(OUT, out);
console.log(`i18n: ${singles.size} strings, ${plurals.size} plurals → ${OUT}`);
